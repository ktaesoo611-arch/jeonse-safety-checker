export interface AddressComponents {
  sigunguCd: string;  // 시군구 코드
  bjdongCd: string;   // 법정동 코드
  platGbCd: string;   // 대지구분코드: 0=대지, 1=산, 2=블록
  bun: string;        // 본번 (main lot number) - 4 digits
  ji: string;         // 부번 (sub lot number) - 4 digits
}

/**
 * Parse Korean address into Building Register API components
 * Supports both Seoul and Gyeonggi-do addresses
 */
export function parseKoreanAddress(address: string): AddressComponents | null {
  // Clean up address
  const cleanAddress = address.trim();

  // Determine if this is a Gyeonggi address
  const isGyeonggi = /경기도|경기\s/.test(cleanAddress);

  // For Gyeonggi, we need to handle "시 구" format (e.g., "성남시 분당구", "수원시 영통구")
  // as well as single-district cities (e.g., "하남시", "부천시")
  let district: string;
  let sigunguCd: string | undefined;
  let dongCodes: Record<string, string> | undefined;

  if (isGyeonggi) {
    // Try to match "XX시 XX구" pattern first (cities with multiple 구)
    const cityGuMatch = cleanAddress.match(/([가-힣]+시)\s+([가-힣]+구)/);
    if (cityGuMatch) {
      // Full "시 구" format
      const fullDistrict = `${cityGuMatch[1]} ${cityGuMatch[2]}`;
      district = fullDistrict;
      sigunguCd = GYEONGGI_DISTRICT_CODES[fullDistrict] || GYEONGGI_DISTRICT_CODES[cityGuMatch[2]];
      dongCodes = GYEONGGI_DONG_CODES[fullDistrict] || GYEONGGI_DONG_CODES[cityGuMatch[2]];
    } else {
      // Try single-district city format (e.g., "하남시", "부천시")
      const cityMatch = cleanAddress.match(/([가-힣]+시)/);
      if (cityMatch) {
        district = cityMatch[1];
        sigunguCd = GYEONGGI_DISTRICT_CODES[district];
        dongCodes = GYEONGGI_DONG_CODES[district];
      } else {
        console.warn('Could not extract city/district from Gyeonggi address:', address);
        return null;
      }
    }

    if (!sigunguCd) {
      console.warn('Unknown Gyeonggi district:', district);
      return null;
    }
  } else {
    // Seoul address - extract 구 only
    const districtMatch = cleanAddress.match(/([가-힣]+구)/);
    if (!districtMatch) {
      console.warn('Could not extract district from address:', address);
      return null;
    }
    district = districtMatch[1];
    sigunguCd = SEOUL_DISTRICT_CODES[district];
    dongCodes = SEOUL_DONG_CODES[district];

    if (!sigunguCd) {
      console.warn('Unknown Seoul district:', district);
      return null;
    }
  }

  // Extract dong (동/로/길) - must come AFTER district
  // First, find where the district ends
  const districtEndIndex = cleanAddress.indexOf(district.split(' ').pop() || district) + (district.split(' ').pop() || district).length;
  const afterDistrict = cleanAddress.substring(districtEndIndex).trim();

  // Patterns to match in order of specificity:
  // - Numbered dong with 가: 광희동2가, 신문로1가, 원효로4가, 종로1가
  // - Regular dong with optional number: 신당동, 신월1동, 목1동, 번1동, 왕십리2동
  // - Road names with 가: 세종로, 충정로, 퇴계로1가
  // - Street names: 덕수궁길
  // - Special names: 디지털단지
  // - Eup/Myeon for rural areas: 진접읍, 남면
  let dongMatch = afterDistrict.match(/^([가-힣]+\d*동\d*가?|[가-힣]+로\d*가?|[가-힣]+길|[가-힣]+\d+가|[가-힣]+읍|[가-힣]+면)/);

  // If standard patterns don't match, try to find a known dong name from dong codes
  if (!dongMatch && dongCodes) {
    const knownDongs = Object.keys(dongCodes);
    for (const knownDong of knownDongs) {
      if (afterDistrict.startsWith(knownDong)) {
        dongMatch = [knownDong, knownDong] as unknown as RegExpMatchArray;
        break;
      }
    }
  }

  if (!dongMatch) {
    console.warn('Could not extract dong from address:', address);
    return null;
  }
  const dong = dongMatch[1];

  // Get dong code
  const bjdongCd = dongCodes?.[dong];
  if (!bjdongCd) {
    console.warn(`Unknown dong: ${dong} in ${district}`);
    // Return null instead of mock data - API won't work with wrong codes
    return null;
  }

  // Extract lot number (번지)
  // Patterns: "435", "123-45", "123번지", etc.
  const lotMatch = cleanAddress.match(/(\d+)(?:-(\d+))?(?:번지)?/);
  if (!lotMatch) {
    console.warn('Could not extract lot number from address:', address);
    return null;
  }

  const bun = lotMatch[1].padStart(4, '0'); // Main lot number (4 digits)
  const ji = (lotMatch[2] || '0').padStart(4, '0'); // Sub lot number (4 digits, default to 0000)

  // Determine platGbCd (대지구분코드)
  // 0 = 대지 (land), 1 = 산 (mountain), 2 = 블록 (block)
  // Check for "산" as a lot type (e.g., "산 123"), not as part of district name
  const platGbCd = /\s산\s|\s산\d/.test(cleanAddress) ? '1' : '0';

  return {
    sigunguCd,
    bjdongCd,
    platGbCd,
    bun,
    ji
  };
}

/**
 * Format address components for display
 */
export function formatAddressComponents(components: AddressComponents): string {
  return `sigunguCd: ${components.sigunguCd}, bjdongCd: ${components.bjdongCd}, platGbCd: ${components.platGbCd}, bun: ${components.bun}, ji: ${components.ji}`;
}

/**
 * Extract 법정동 (legal dong) name from a 지번주소 (lot-based address)
 *
 * Examples:
 * - "서울특별시 중구 신당동 123-45" → "신당동"
 * - "서울 중구 광희동2가 789" → "광희동2가"
 * - "경기도 성남시 분당구 정자동 12-3" → "정자동"
 *
 * @param jibunAddress - Lot-based address (지번주소)
 * @returns The legal dong name, or null if not found
 */
export function extractLegalDongFromJibunAddress(jibunAddress: string): string | null {
  if (!jibunAddress) return null;

  // Pattern to match Korean dong names:
  // - Regular dong: 신당동, 정자동, 미사동
  // - Numbered dong: 광희동2가, 신문로1가, 필동3가
  // - Also handles: 동1가, 동2가 format
  const dongMatch = jibunAddress.match(/([가-힣]+동\d*가?|[가-힣]+\d+가)/);

  if (dongMatch) {
    return dongMatch[1];
  }

  return null;
}

/**
 * Check if an address is a road name address (도로명주소) vs lot address (지번주소)
 *
 * Road name addresses contain patterns like "XX로", "XX길", "XX대로"
 * Lot addresses contain patterns like "XX동 123-45"
 *
 * @param address - Address string to check
 * @returns true if road name address, false if lot address
 */
export function isRoadNameAddress(address: string): boolean {
  // Road name patterns: XX로, XX길, XX대로
  const roadPattern = /[가-힣]+[로길](\d+[가-힣]*)?(\s+\d+(-\d+)?)?/;
  // Lot address pattern: XX동 followed by number
  const lotPattern = /[가-힣]+동\d*가?\s+\d+/;

  const hasRoadPattern = roadPattern.test(address);
  const hasLotPattern = lotPattern.test(address);

  // If has road pattern and no lot pattern, it's a road address
  // If has lot pattern, it's a lot address
  if (hasLotPattern) return false;
  if (hasRoadPattern) return true;

  // Default: assume road address if ambiguous
  return true;
}

/**
 * Get all valid dong names for a district
 * Supports both Seoul and Gyeonggi districts
 *
 * @param district - District name (e.g., "중구", "강남구", "성남시 분당구", "하남시")
 * @returns Array of valid dong names for the district
 */
export function getValidDongsForDistrict(district: string): string[] {
  // Try Seoul first
  const seoulDongs = SEOUL_DONG_CODES[district];
  if (seoulDongs) return Object.keys(seoulDongs);

  // Try Gyeonggi
  const gyeonggiDongs = GYEONGGI_DONG_CODES[district];
  if (gyeonggiDongs) return Object.keys(gyeonggiDongs);

  return [];
}
